import 'package:o_jogo_da_obra/core/data/models/data_convertible.dart';
import 'package:o_jogo_da_obra/core/utils/extensions/date_time_extension.dart';
import 'package:o_jogo_da_obra/core/utils/type_defs.dart';
import 'package:o_jogo_da_obra/features/maintenance_plans/domain/entities/interval_unit.dart';
import 'package:o_jogo_da_obra/features/maintenance_plans/domain/entities/maintenance_plan_entity.dart';
import 'package:o_jogo_da_obra/features/work_orders/domain/entities/priority.dart';

class MaintenancePlanModel extends MaintenancePlanEntity
    implements DataConvertible<MaintenancePlanEntity> {
  const MaintenancePlanModel({
    required super.id,
    required super.companyId,
    super.locationId,
    super.assetId,
    super.areaId,
    super.assignedToId,
    super.serviceProviderCompanyId,
    super.checklistTemplateId,
    required super.title,
    super.description,
    required super.priority,
    super.price,
    super.currency = 'BRL',
    required super.intervalValue,
    required super.intervalUnit,
    required super.leadTimeDays,
    required super.durationDays,
    super.dayOfWeek,
    super.dayOfMonth,
    super.monthOfYear,
    required super.isActive,
    super.lastGeneratedAt,
    super.lastGeneratedWorkOrderId,
    super.lastError,
    super.nextDueDate,
    required super.createdAt,
    required super.updatedAt,
    super.deletedAt,
  });

  factory MaintenancePlanModel.fromEntity(MaintenancePlanEntity entity) =>
      MaintenancePlanModel(
        id: entity.id,
        companyId: entity.companyId,
        locationId: entity.locationId,
        assetId: entity.assetId,
        areaId: entity.areaId,
        assignedToId: entity.assignedToId,
        serviceProviderCompanyId: entity.serviceProviderCompanyId,
        checklistTemplateId: entity.checklistTemplateId,
        title: entity.title,
        description: entity.description,
        priority: entity.priority,
        price: entity.price,
        currency: entity.currency,
        intervalValue: entity.intervalValue,
        intervalUnit: entity.intervalUnit,
        leadTimeDays: entity.leadTimeDays,
        durationDays: entity.durationDays,
        dayOfWeek: entity.dayOfWeek,
        dayOfMonth: entity.dayOfMonth,
        monthOfYear: entity.monthOfYear,
        isActive: entity.isActive,
        lastGeneratedAt: entity.lastGeneratedAt,
        lastGeneratedWorkOrderId: entity.lastGeneratedWorkOrderId,
        lastError: entity.lastError,
        nextDueDate: entity.nextDueDate,
        createdAt: entity.createdAt,
        updatedAt: entity.updatedAt,
        deletedAt: entity.deletedAt,
      );

  factory MaintenancePlanModel.fromJson(
    MapDynamic json,
  ) => MaintenancePlanModel(
    id: json['id'] as String? ?? '',
    companyId: json['company_id'] as String? ?? '',
    locationId: json['location_id'] as String?,
    assetId: json['asset_id'] as String?,
    areaId: json['area_id'] as String?,
    assignedToId: json['assigned_to_id'] as String?,
    serviceProviderCompanyId: json['service_provider_company_id'] as String?,
    checklistTemplateId: json['checklist_template_id'] as String?,
    title: json['title'] as String? ?? '',
    description: json['description'] as String?,
    priority: Priority.fromCode(json['priority'] as String? ?? 'medium'),
    price: (json['price'] as num?)?.toDouble(),
    currency: json['currency'] as String? ?? 'BRL',
    intervalValue: json['interval_value'] as int? ?? 1,
    intervalUnit: IntervalUnit.fromCode(
      json['interval_unit'] as String? ?? 'months',
    ),
    leadTimeDays: json['lead_time_days'] as int? ?? 0,
    durationDays: json['duration_days'] as int? ?? 1,
    dayOfWeek: json['day_of_week'] as int?,
    dayOfMonth: json['day_of_month'] as int?,
    monthOfYear: json['month_of_year'] as int?,
    isActive: json['is_active'] as bool? ?? true,
    lastGeneratedAt: (json['last_generated_at'] as String?).toUtcDateTime(),
    lastGeneratedWorkOrderId: json['last_generated_work_order_id'] as String?,
    lastError: json['last_error'] as String?,
    nextDueDate: (json['next_due_date'] as String?).toUtcDateTime(),
    createdAt:
        (json['created_at'] as String?).toUtcDateTime() ??
        DateTime.now().toUtc(),
    updatedAt:
        (json['updated_at'] as String?).toUtcDateTime() ??
        DateTime.now().toUtc(),
    deletedAt: (json['deleted_at'] as String?).toUtcDateTime(),
  );

  @override
  MapDynamic toJson() => {
    'id': id,
    'company_id': companyId,
    'location_id': locationId,
    'asset_id': assetId,
    'area_id': areaId,
    'assigned_to_id': assignedToId,
    'service_provider_company_id': serviceProviderCompanyId,
    'checklist_template_id': checklistTemplateId,
    'title': title,
    'description': description,
    'priority': priority.code,
    'price': price,
    'currency': currency,
    'interval_value': intervalValue,
    'interval_unit': intervalUnit.code,
    'lead_time_days': leadTimeDays,
    'duration_days': durationDays,
    'day_of_week': dayOfWeek,
    'day_of_month': dayOfMonth,
    'month_of_year': monthOfYear,
    'is_active': isActive,
    'last_generated_at': lastGeneratedAt?.toIsoUtcString(),
    'last_generated_work_order_id': lastGeneratedWorkOrderId,
    'last_error': lastError,
    'next_due_date': nextDueDate?.toIsoUtcString(),
    'created_at': createdAt.toIsoUtcString(),
    'updated_at': updatedAt.toIsoUtcString(),
    'deleted_at': deletedAt?.toIsoUtcString(),
  };

  @override
  MaintenancePlanEntity toEntity() => MaintenancePlanEntity(
    id: id,
    companyId: companyId,
    locationId: locationId,
    assetId: assetId,
    areaId: areaId,
    assignedToId: assignedToId,
    serviceProviderCompanyId: serviceProviderCompanyId,
    checklistTemplateId: checklistTemplateId,
    title: title,
    description: description,
    priority: priority,
    price: price,
    currency: currency,
    intervalValue: intervalValue,
    intervalUnit: intervalUnit,
    leadTimeDays: leadTimeDays,
    durationDays: durationDays,
    dayOfWeek: dayOfWeek,
    dayOfMonth: dayOfMonth,
    monthOfYear: monthOfYear,
    isActive: isActive,
    lastGeneratedAt: lastGeneratedAt,
    lastGeneratedWorkOrderId: lastGeneratedWorkOrderId,
    lastError: lastError,
    nextDueDate: nextDueDate,
    createdAt: createdAt,
    updatedAt: updatedAt,
    deletedAt: deletedAt,
  );
}
